// 변수의 주소

#include <stdio.h>

int main(void) {
    int i = 10; 
    char c = 69;
    float f = 12.3;

    printf("i의 주소: %p\n", &i);
    printf("c의 주소: %p\n", &c);
    printf("f의 주소: %p\n", &f);

    //          <메모리>
    //         (스택영역)
    //  높은 주소에서 낮은 주소로
    //    <--     <--      <--
    // |-------|--------|--------|
    // |   f   |   c    |   i    |
    // |-------|--------|--------|
    // |  12.3 |   69   |   10   |
    // |-------|--------|--------| 
    
    // (상대적으로) 낮은 주소                       높은 주소
    // 힙 영역[ 1, 2, 3, . . . -> (여유 공간) <- . . . 3, 2, 1 ] 스택 영역

    return 0;
}