// 전역 변수의 사용

/**
 * 전역 변수 하나를 여러 함수가 공유하면 서로 영향을 줄 수 있다
 * - 전역 변수는 여러 함수가 공통으로 사용하는 데이터를 공유할 때 유용
 * - 단, 여러 함수에서 값을 변경하면 관리가 어려워질 수 있으므로 사용에 주의
 */

#include <stdio.h>

int x;  // 0으로 자동 초기화됨

void sub(void) {
    for(x = 0; x < 10; x++)
        printf("*");
}

int main(void) {
    for (x = 0; x < 10; x++)
        sub();

    return 0;
}

/**
 * main 함수에서 for 문의 x가 0일때, sub 함수 호출
 * sub 함수 안에서 printf("*"); 를 10번 수행한 후 메인 함수로 복귀
 * sub 함수에서 반복문을 돌며 x가 10이 됨
 * main의 for 문이 끝남
 */