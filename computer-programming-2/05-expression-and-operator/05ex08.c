// 예제 #8. 관계 연산자

#include <stdio.h>

int main(void)
{
    int x, y;

    printf("정수 2개 입력: ");
    scanf("%d %d", &x, &y);

    printf("x == y 결과: %d\n", x==y);
    printf("x != y 결과: %d\n", x!=y);
    printf("x > y 결과: %d\n", x>y);
    printf("x < y 결과: %d\n", x<y);
    printf("x >= y 결과: %d\n", x>=y);
    printf("x <= y 결과: %d\n", x<=y);
}