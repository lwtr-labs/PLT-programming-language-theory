// 예제 #11. 윤년 계산

// 윤년의 조건
//   - 연도가 4로 나누어 떨어진다 -> 4의 배수 포함
//   - 100으로 나누어 떨어지는 연도는 제외한다. -> 100의 배수 제외
//   - 400으로 나누어 떨어지는 연도는 윤년이다. -> 400의 배수 포함

// 즉, 4의 배수이며 100의 배수이거나 400의 배수이다.

#include <stdio.h>

int main(void) {
    int year, result;

    printf("계산할 연도 입력: ");
    scanf("%d", &year);

    result = ((year % 4 == 0) && (year % 100 != 0)) || (year % 400 == 0);
    printf("윤년 여부(1: 윤년, 0(평년)) = %d \n", result);

    return 0;
}   