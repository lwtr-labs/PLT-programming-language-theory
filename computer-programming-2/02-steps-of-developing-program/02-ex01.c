// 예제 #1. 두 줄 출력

#include <stdio.h>

int main(void) {

    
    printf("\n--- 첫 번째 구현 시도 ---\n");

    // 첫 번째 구현 시도.
    printf("Hello World!"); 
    printf("C Programming");    // 2개의 문장은 순차적으로 실행된다.
    
    // 실행을 해보면 결과는..
    // Hello World!C Programming

    printf("\n\n--- 두 번째 구현 시도 ---\n");
    // 두 번째 구현 시도 (줄바꿈 문자를 추가)

    printf("Hello World!\n");
    printf("C Programming");



    printf("\n\n");
    return 0;
}