// 예제 #3. 사칙연산
// 덧셈, 뺄셈, 곱셈, 나눗셈 계산을 하는 프로그램을 작성해보자.

// 출력 예

// 3 + 4 = 7
// 3 - 4 = -1
// 3 * 4 = 12
// 3 / 4 = 0

// 조건

// 1.
// printf() 안에 직접 전체 수식을 타이핑 한다.
//  -> 모두 문자열로 화면에 단순히 출력만 함.

//2.
// printf()와 수식을 적절히 함께 사용한다.
//  -> 문자열 뿐만 아니라 정수, 연산을 함께 사용.

#include <stdio.h>

int main(void) {
    printf("3 + 4 = %d\n", 3 + 4);
    printf("3 - 4 = %d\n", 3 - 4);
    printf("3 * 4 = %d\n", 3 * 4);
    printf("3 / 4 = %d\n", 3 / 4);

    return 0;
}